// README.md's generated blocks, rewritten from QMBL's current data and results/ (
// 2026-10-09: the README laid out as QMBL's): the badges, the leaderboard and the citation. The
// leaderboard is what qmbl.org's Open Problems pages show: the systems and the entries once there
// are any, and every open problem, one collapsed table per model. As in QMBL, where a stale
// leaderboard in the README is the worst failure the repository has available, the blocks are
// never edited by hand: .github/workflows/readme.yml rewrites them every day, after every push to
// main that changes results/ or the target code, and when started by hand.
//
// The scoring and the labels are QMBL's own code, so the README, the pages and QMBL's README
// cannot disagree: scripts/open_problems.mjs (loadOpenProblems, score), which builds the pages,
// and scripts/readme_table.mjs (instance labels, quoting, markers), which writes QMBL's README.
// The citation comes from this repository's CITATION.cff. QMBL is read from a checkout of its repository at
// QMBL_DIR, by default ../qmbl beside this one; CI checks it out into qmbl/.
//
// Until launch day QMBL's main branch has no scripts/open_problems.mjs (the pages are merged
// then). With such a checkout this script says so and leaves README.md as it is.
//
// No dependencies. Run:  QMBL_DIR=../qmbl node scripts/readme.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadQmbl } from "./targets.mjs";
import { citationOf } from "./citation.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const README = path.join(ROOT, "README.md");
const QMBL = path.resolve(process.env.QMBL_DIR ?? path.join(ROOT, "..", "qmbl"));
const begin = name => `<!-- BEGIN ${name} (generated by scripts/readme.mjs - do not edit) -->`;
const end = name => `<!-- END ${name} -->`;

// Free text in a table cell: a pipe would end the cell.
const cell = s => String(s).replace(/\|/g, "\\|");
// Relative, with its sign, as on the pages: below the target is what the list is about.
const gapText = g => (g == null ? "n/a" : g === 0 ? "0" : `${g < 0 ? "−" : "+"}${Math.abs(g).toExponential(1)}`);
// A static shields.io badge: in its path a dash is written twice and an underscore twice.
const badge = (label, message, colour) =>
  `https://img.shields.io/badge/${[label, message].map(s => encodeURIComponent(String(s).replace(/-/g, "--").replace(/_/g, "__"))).join("-")}-${colour}`;

// The citation (title, authors, concept DOI, year) from a CITATION.cff: scripts/citation.mjs.
export { citationOf };

// Spliced by index, never by String.replace: a replacement containing $' or $& would paste the
// file into itself.
export function splice(text, name, lines) {
  const b = begin(name), e = end(name), i = text.indexOf(b), j = text.indexOf(e);
  if (i < 0 || j < i) throw new Error(`README.md is missing the ${name} markers`);
  return text.slice(0, i) + `${b}\n\n${lines.join("\n").trimEnd()}\n\n${e}` + text.slice(j + e.length);
}

async function main() {
  if (!fs.existsSync(path.join(QMBL, "scripts/open_problems.mjs"))) {
    console.log(`readme: ${QMBL} has no scripts/open_problems.mjs (QMBL's Open Problems pages are not on that branch yet), so README.md stays as it is`);
    return;
  }
  const qmbl = f => import(pathToFileURL(path.join(QMBL, "scripts", f)).href);
  const [ops, units, table, cite, enrich] = await Promise.all(
    ["open_problems.mjs", "units.mjs", "readme_table.mjs", "cite.mjs", "enrich_sources.mjs"].map(qmbl));
  const { loadOpenProblems, score, AI_LABELS, LINKS } = ops;
  if (typeof score !== "function" || !AI_LABELS || !LINKS)
    throw new Error(`${QMBL}/scripts/open_problems.mjs does not export score, AI_LABELS and LINKS`);
  const { instances, perSiteDivisor } = await loadQmbl(QMBL);
  const op = await loadOpenProblems(instances, ROOT);
  const { targets, entries, systems } = score(op, instances);
  const { title, head, doi, year } = citationOf(fs.readFileSync(path.join(ROOT, "CITATION.cff"), "utf8"));
  // QMBL's source cache (paper names and links) lives in its checkout, under sources/.
  const cwd = process.cwd();
  process.chdir(QMBL);
  let cache;
  try { cache = enrich.sources(); } finally { process.chdir(cwd); }

  const known = new Set(table.MODELS.map(([m]) => m));
  for (const x of targets) if (!known.has(x.inst.model)) throw new Error(`${x.inst.instance_id}: model ${x.inst.model} has no MODELS entry`);
  const modelName = new Map(table.MODELS);
  const groups = table.MODELS.map(([model, name]) => [name, targets.filter(x => x.inst.model === model).sort((a, b) => table.byGeometry(a.inst, b.inst))])
    .filter(([, g]) => g.length);

  // A QMBL row as QMBL's README quotes it: per site, to its error bar, with its markers after.
  const quoted = (row, inst) => {
    const f = perSiteDivisor(inst) ?? 1;
    return table.quote(row.energy / f, row.sigma == null ? null : row.sigma / f).text;
  };
  const method = row => `${cell(table.shorten(units.methodLabel(row), 46))} ${cite.citeCell(row, cache)}`;
  const targetRow = ({ t, inst, row, estimate, first }) => {
    const [beat, how] = row ? [`**${quoted(row, inst)}**${table.marks(row)}`, method(row)]
      : first ? [`**${table.quote(first.energy_per_site, first.sigma_per_site).text}**`, `${cell(first.system)}, the first verified state`]
      : ["none yet", "the first verified state sets it"];
    const est = estimate ? `${quoted(estimate, inst)}${table.marks(estimate)} ${units.boundLabel(estimate)}, ${cite.citeCell(estimate, cache)}` : "";
    const verifier = t.verifier.supported ? "yes" : `not yet (${cell(t.verifier.reason)})`;
    return `| ${table.instanceLabel(inst)} | ${beat} | ${how} | ${est} | ${verifier} |`;
  };

  // Only once there are entries, as on the pages (2026-10-09): the systems above the
  // problems, the entries under them.
  const systemsBlock = systems.length ? [
    "### Systems", "",
    "Lowest median gap first; only a system's live, verified entries on open instances count.", "",
    "| system | team | AI | median gap | instances | records |", "|---|---|---|---|---|---|",
    ...systems.map(s => `| ${cell(s.system)} | ${cell(s.teams.join(", "))} | ${s.ai.map(a => AI_LABELS[a]).join(", ")} | ${gapText(s.median)} | ${s.instances} | ${s.records} |`),
    ""] : [];

  const measurable = targets.filter(x => x.t.verifier.supported).length;
  const problemsBlock = [
    `### All ${targets.length} open problems (click to unravel)`, "",
    `The verifier can measure ${measurable} of them today.`, "",
    // GitHub only renders a table inside <details> when a blank line follows <summary>.
    ...groups.flatMap(([name, g]) => [
      "<details>",
      `<summary><b>${name}</b>: ${g.length} instance${g.length === 1 ? "" : "s"}, energies as <code>${units.perSiteLabel(g[0].inst)}</code></summary>`, "",
      "| instance | energy to beat | method | record (estimate) | verifier |", "|---|---|---|---|---|",
      ...g.map(targetRow), "", "</details>", ""]),
  ];

  const order = new Map(groups.flatMap(([, g]) => g).map((x, k) => [x, k]));
  const rank = s => order.get(s.x) ?? order.size;
  const links = l => LINKS.filter(([k]) => /^https:\/\//.test(l?.[k] ?? "")).map(([k, label]) => `[${label}](${l[k]})`).join(", ") || "n/a";
  const compute = c => {
    const h = v => Number(v).toLocaleString("en-US", { maximumFractionDigits: 1 });
    const parts = [c?.hardware, c?.gpu_hours != null && `${h(c.gpu_hours)} GPU-hours`, c?.cpu_core_hours != null && `${h(c.cpu_core_hours)} CPU core-hours`].filter(Boolean);
    return parts.length ? cell(parts.join(", ")) : "n/a";
  };
  const entriesBlock = entries.length ? [
    "### Entries", "",
    "| instance | system | team | AI | energy, re-measured | gap | compute | links |", "|---|---|---|---|---|---|---|---|",
    ...[...entries].sort((a, b) => rank(a) - rank(b) || a.e.energy_per_site - b.e.energy_per_site).map(s => {
      const gap = (s.solved ? "solved" : s.first ? "first state" : gapText(s.gap)) + (s.record ? ", new record" : "");
      const flag = s.flagged ? ` (flagged: ${cell(s.e.flags.join("; "))})` : "";
      return `| ${modelName.get(s.x.inst.model)} ${table.instanceLabel(s.x.inst)} | ${cell(s.e.system)}${s.live ? "" : " (replaced)"}${flag} | ${cell(s.e.team)} | ${AI_LABELS[s.e.ai_involvement]} | ${table.quote(s.e.energy_per_site, s.e.sigma_per_site).text} ${units.perSiteLabel(s.x.inst)} | ${gap} | ${compute(s.e.compute)} | ${links(s.e.links)} |`;
    }), ""] : [];

  const badges = [
    `[![DOI](${badge("DOI", doi, "1682D4")})](https://doi.org/${doi})`,
    `[![License: Apache 2.0](${badge("license", "Apache-2.0", "blue")})](LICENSE)`,
    `[![open problems](${badge("open problems", targets.length, "104281")})](#leaderboard)`,
    `[![entries](${badge("entries", entries.length, "success")})](#leaderboard)`,
    `[![status: beta](${badge("status", "beta", "eb6834")})](#details)`,
  ];
  const citation = [
    "Cite QMBL: Open Problems by its concept DOI, which always resolves to the latest release:", "",
    `> ${head}, *${title}*, Zenodo (${year}).`,
    `> [${doi}](https://doi.org/${doi})`, "",
    "Individual energies should cite the primary paper named on the row, not this repository.",
  ];

  const before = fs.readFileSync(README, "utf8");
  let text = before;
  text = splice(text, "BADGES", badges);
  text = splice(text, "LEADERBOARD", [...systemsBlock, ...problemsBlock, ...entriesBlock]);
  text = splice(text, "CITATION", citation);
  const what = `${targets.length} open problems (${measurable} measurable), ${entries.length} entries, ${systems.length} systems`;
  if (text === before) console.log(`README.md unchanged: ${what}`);
  else {
    fs.writeFileSync(README, text);
    console.log(`README.md rewritten: ${what}`);
  }
}

// Side effect only when run directly: the tests import citationOf and splice.
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) await main();
