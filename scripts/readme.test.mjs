// Tests for the parts of scripts/readme.mjs that need no QMBL checkout: the citation read from
// QMBL's CITATION.cff and the splicing of a generated block. Run: node --test scripts/readme.test.mjs
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import { citationOf, splice } from "./readme.mjs";

const CONCEPT = `  - type: doi
    value: 10.5281/zenodo.22753734
    description: "Concept DOI - always resolves to the latest release"
`;
const VERSION = `  - type: doi
    value: 10.5281/zenodo.23239245
    description: "v0.4.0 snapshot: 395 instances, 1434 rows, 395 records"
`;
const cff = identifiers => `cff-version: 1.2.0
title: "QMBL: the Quantum Many-Body Leaderboard"
authors:
  - family-names: Zerweck
    given-names: Tristan
  - family-names: Carrasquilla
    given-names: Juan
version: 0.4.0
date-released: "2026-10-08"
doi: 10.5281/zenodo.22753734
identifiers:
${identifiers}`;

test("citation: the title, the authors by initial, the concept DOI and the year of the latest release", () => {
  assert.deepEqual(citationOf(cff(CONCEPT + VERSION)), { title: "QMBL: the Quantum Many-Body Leaderboard", head: "T. Zerweck and J. Carrasquilla", doi: "10.5281/zenodo.22753734", year: "2026" });
});

test("citation: the concept DOI even where a version DOI is listed first", () => {
  assert.equal(citationOf(cff(VERSION + CONCEPT)).doi, "10.5281/zenodo.22753734");
});

test("citation: this repository's own CITATION.cff", () => {
  const own = citationOf(fs.readFileSync(new URL("../CITATION.cff", import.meta.url), "utf8"));
  assert.deepEqual(own, { title: "QMBL: Open Problems", head: "T. Zerweck and J. Carrasquilla", doi: "10.5281/zenodo.23439787", year: "2026" });
});

test("citation: a CITATION.cff without authors is an error, not an empty citation", () => {
  assert.throws(() => citationOf('title: "QMBL"\ndoi: 10.5281/zenodo.1\ndate-released: "2026-01-01"\n'), /authors/);
});

test("splice: only the named block changes, and $' and $& in the new text stay as they are", () => {
  const text = "a\n<!-- BEGIN X (generated by scripts/readme.mjs - do not edit) -->\nold\n<!-- END X -->\nb\n";
  assert.equal(splice(text, "X", ["new $' $& line", ""]),
    "a\n<!-- BEGIN X (generated by scripts/readme.mjs - do not edit) -->\n\nnew $' $& line\n\n<!-- END X -->\nb\n");
});

test("splice: a block without its markers is an error", () => {
  assert.throws(() => splice("no markers here", "X", ["y"]), /X markers/);
});

test("README.md carries the markers of every generated block", () => {
  const readme = fs.readFileSync(new URL("../README.md", import.meta.url), "utf8");
  for (const name of ["BADGES", "LEADERBOARD", "CITATION"]) assert.doesNotThrow(() => splice(readme, name, []), name);
});
